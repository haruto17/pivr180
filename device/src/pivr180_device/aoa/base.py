from collections.abc import Hashable
from typing import Protocol


class AccessoryPort(Protocol):
    def read(self) -> bytes: ...

    def write(self, data: bytes) -> None: ...

    def close(self) -> None: ...


class UsbDevice(Protocol):
    @property
    def key(self) -> Hashable: ...

    @property
    def name(self) -> str: ...

    @property
    def vendor_id(self) -> int: ...

    @property
    def product_id(self) -> int: ...

    @property
    def device_class(self) -> int: ...

    @property
    def interface_classes(self) -> frozenset[int]: ...

    def control_in(self, request: int, length: int) -> bytes: ...

    def control_out(self, request: int, index: int, data: bytes) -> None: ...

    def reset(self) -> None: ...

    def open_accessory(self) -> AccessoryPort: ...


class UsbBus(Protocol):
    def devices(self) -> list[UsbDevice]: ...
